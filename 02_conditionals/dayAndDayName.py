#take a day number and display day name

number = int(input("Enter a number between 1 to 7: "))

if number == 1:
    print("its sunday")
elif number == 2:
    print("its Monday")
elif number == 3:
    print("its Tuesday")
elif number == 4:
    print("its Wednesday")
elif number == 5:
    print("its Thursday")
elif number == 6:
    print("its Friday")
elif number == 7:
    print("its Saturday")
else:
    print("invalid date or number")
