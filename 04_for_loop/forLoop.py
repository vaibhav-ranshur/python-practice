"""
A for loop is used when you want to repeat something for each item in a collection
(list, string, tuple, etc.) or for a fixed number of times.

Why use a for loop?

Suppose you want to print numbers 1 to 5.

Without a loop:

print(1)
print(2)
print(3)
print(4)
print(5)

"""
# with a for loop:

for i in range(1, 6):
    print(i)

# another example with string

msg = "HELLO"

for x in msg:
    print(x)

